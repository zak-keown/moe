describe('emitDocs with the real claude-code adapter (proves the pipe end to end)', () => {
  it('emits docs/install/claude-code.md with the marker, heading, and installDoc body', () => {
    const files = emitDocs(model, [claudeCode])
    const file = files.find((f) => f.path === 'docs/install/claude-code.md')!
    expect(file.content).toBe(
      [
        '<!-- GENERATED by moe-mint — edit moe-mint.yaml instead -->',
        '',
        '# Installing kitchen-sink on Claude Code',
        '',
        claudeCode.installDoc!(model),
        '',
      ].join('\n'),
    )
  })

  it('emits one docs/install/<name>.md per adapter for the real 8-adapter registry (every adapter implements installDoc)', () => {
    const files = emitDocs(model, adapters)
    const installDocPaths = files.filter((f) => f.path.startsWith('docs/install/')).map((f) => f.path)
    expect(installDocPaths.sort()).toEqual(
      adapters.map((a) => `docs/install/${a.name}.md`).sort(),
    )
  })
})

