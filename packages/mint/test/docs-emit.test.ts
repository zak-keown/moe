const model = buildModel('fixtures/kitchen-sink')

function tmpFixture(yaml: string): string {
  const dir = mkdtempSync(join(tmpdir(), 'mint-docs-emit-'))
  writeFileSync(join(dir, 'moe-mint.yaml'), withV1Policy(yaml))
  return dir
}

